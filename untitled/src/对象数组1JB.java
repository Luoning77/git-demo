public class 对象数组1JB {
    private String id;
    private String name;
    private double jg;
    private int kc;

    private String name1;
    private Double jg1;
    private String ys;

    public 对象数组1JB() {

    }

    public 对象数组1JB(String id, String name, double jg, int kc) {
        this.id = id;
        this.name = name;
        this.jg = jg;
        this.kc = kc;
    }

    public 对象数组1JB(String name1, Double jg1, String ys) {
        this.name1 = name1;
        this.jg1 = jg1;
        this.ys = ys;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public double getJg() {
        return jg;
    }

    public void setJg(double jg) {
        this.jg = jg;
    }

    public int getKc() {
        return kc;
    }

    public void setKc(int kc) {
        this.kc = kc;
    }


    public String getName1() {
        return name1;
    }

    public void setName1(String name1) {
        this.name1 = name1;
    }

    public double getJg1() {
        return jg1;
    }

    public void setJg1(Double jg1) {
        this.jg1 = jg1;
    }

    public String getYs() {
        return ys;
    }

    public void setYs(String ys) {
        this.ys = ys;
    }
}
