public class 集合练习查信息JB {
    private String id;
    private String name;
    private String mm;

    public 集合练习查信息JB() {
    }
    public 集合练习查信息JB(String id, String name, String mm) {
        this.id = id;
        this.name = name;
        this.mm = mm;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getMm() {
        return mm;
    }

    public void setMm(String mm) {
        this.mm = mm;
    }
}
